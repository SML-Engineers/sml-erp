# code -> (label, report section, normal balance). The order is the order of the reports.
TYPES = {
    "bank": ("Bank", ASSETS, "debit"),
    "accounts_receivable": ("Accounts receivable", ASSETS, "debit"),
    "other_current_asset": ("Other current asset", ASSETS, "debit"),
    "fixed_asset": ("Fixed asset", ASSETS, "debit"),
    "other_asset": ("Other asset", ASSETS, "debit"),
    "accounts_payable": ("Accounts payable", LIABILITIES, "credit"),
    "credit_card": ("Credit card", LIABILITIES, "credit"),
    "other_current_liability": ("Other current liability", LIABILITIES, "credit"),
    "long_term_liability": ("Long-term liability", LIABILITIES, "credit"),
    "equity": ("Equity", EQUITY, "credit"),
    "income": ("Income", PROFIT_AND_LOSS, "credit"),
    "other_income": ("Other income", PROFIT_AND_LOSS, "credit"),
    "cost_of_goods_sold": ("Cost of goods sold", PROFIT_AND_LOSS, "debit"),
    "expense": ("Expense", PROFIT_AND_LOSS, "debit"),
    "other_expense": ("Other expense", PROFIT_AND_LOSS, "debit"),
}
TYPE_CHOICES = [(code, label) for code, (label, _, _) in TYPES.items()]
TYPE_ORDER = {code: index for index, code in enumerate(TYPES)}


def section_of(account_type: str) -> str:
    return TYPES[account_type][1]


