"""Account types, report sections and the starter detail types (spec 3, backlog P0-15).

The account types are fixed, as in QuickBooks: they decide where an account appears in the
reports and whether its balance is normally a debit or a credit. The detail types refine a
type and are an editable list; the ones below are only the starting list (migration 0002).
"""

